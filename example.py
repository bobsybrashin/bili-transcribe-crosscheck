#!/usr/bin/env python3
"""不用 API key、不联网，30 行看懂这套方法为什么有用。

    python3 example.py

下面两段文字是**编的**，不是任何真实转写。它们模拟同一段音频的两个独立来源：
  源A = 平台自动字幕（无标点，已知会整段丢内容）
  源B = 付费 ASR（有标点）

里面埋了四类问题，各自对应一种检测。先看结构质检（四道闸）怎么判——
它会说「pass」。这就是做双源交叉核验的全部理由：**单源看不出自己的错。**
"""
import sys, pathlib
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent / 'src'))
import qc

# 源B：假设它是对的
B = (
    '今天我们聊一个被低估的问题，就是城市供水管网的漏损率。根据行业年鉴的口径，'
    '全国平均漏损率大概在百分之十三左右，但这个数字掩盖了巨大的地区差异。'
    '北方一些老城区的管网是一九七零年铺设的，材质以灰口铸铁为主，接口老化以后渗漏几乎不可避免。'
    '我们在华东做过一个样本调查，选了十二个地级市，统计口径统一到出厂水量减去计费水量。'
    '结论是漏损率的中位数偏高，最高的一个市更是远超预期。'
    '这里要特别强调，漏损不等于爆管。爆管是显性的，抢修队两小时就到现场；'
    '真正难办的是背景漏失，它常年存在，你在地面上看不到任何痕迹。'
    '所以检漏这件事不能靠报修电话，必须靠分区计量。'
    '把管网切成若干个独立计量区，夜间最小流量一测就知道哪个区有问题。'
    '这套办法在国外已经用了很多年，我们推广得并不快，原因不是技术，是钱和产权。'
)

# 源A：同一段音频的另一套转写。四处不同，分别是四类典型问题
A = (
    '今天我们聊一个被低估的问题就是城市供水管网的漏损率根据行业年鉴的口径'
    '全国平均漏损率大概在百分之十三左右但这个数字掩盖了巨大的地区差异'
    '北方一些老城区的管网是一九八零年铺设的材质以灰口柱体为主接口老化以后渗漏几乎不可避免'   # ← 数字 + 替换
    '我们在华东做过一个样本调查选了十二个地级市统计口径统一到出厂水量减去计费水量'
    '结论是漏损率的中位数偏高最高的一个市更是远超预期'
    '这里要特别强调漏损不等于爆管爆管是显性的'                                      # ← 整句没了
    '真正难办的是背景漏失它常年存在你在地面上看不到任何痕迹'
    '所以检漏这件事不能靠报修电话必须靠分区计量'
    '把管网切成若干个独立计量区夜间最小流量一测就知道哪个区有问题'
    '这套办法在国外已经用了很多年我们推广得并不快原因是技术是钱和产权'                  # ← 否定词没了
)

DUR = 180          # 假设这段音频 3 分钟
line = lambda c='─': print(c * 66)


def main():
    line('━')
    print('一、结构质检（四道闸）看源A —— 单源能看出什么')
    line()
    g = qc.gates(A, [A[i:i + 20] for i in range(0, len(A), 20)], DUR * 0.98, DUR)
    for k in ('chars', 'cps', 'loop', 'tail'):
        print(f'  {k:<6} {g[k]}')
    print(f'  判定    {g["qc"].upper()}   {g["bad"] or "四道闸全过"}')
    print()
    print('  ↑ 源A 少了一整句、错了两个词、丢了一个否定词，四道闸一个都没响。')
    print('    字数正常、密度正常、不循环、没截断——因为删完之后文字仍然通顺。')

    print()
    line('━')
    print('二、双源交叉核验 —— 拿第二个来源去查第一个')
    line()

    div = qc.divergence(A, B)
    print(f'  divergence()   {len(div)} 处')
    for d in div:
        print(f'     [{d["kind"]}] …{d["ctx"][-12:]}')
        print(f'          源A: {d["a"] or "（没有）"}')
        print(f'          源B: {d["b"] or "（没有）"}')

    neg = qc.negation_check(A, B)
    print(f'\n  negation_check()   {len(neg)} 处'
          '      ← 一字之差可翻转语义，长度阈值必然漏掉，所以单独查')
    for d in neg:
        print(f'     …{d["ctx"][-12:]} ｜ 源A: {d["a"] or "（没有）"}  源B: {d["b"] or "（没有）"}')

    num = qc.number_check(A, B)
    print(f'\n  number_check()   {len(num)} 处'
          '        ← 数字没有语义冗余，读上去不会别扭，只能靠数')
    for d in num:
        print(f'     {d["v"]}：源A 出现 {d["a"]} 次，源B 出现 {d["b"]} 次')

    lone, nw, nu = qc.lone_words(A)
    print(f'\n  lone_words()   {len(lone)} 个'
          f'（全文英文词 {nw} 个）  ← 纯中文内容里这条通道是废的，坑表里有')

    print()
    line('━')
    print('三、结论')
    line()
    print(f'  四道闸：{g["qc"]}          双源核验：{len(div) + len(neg) + len(num)} 处待核')
    print()
    print('  四类问题各归各的检测，少一类就漏一类：')
    print('    替换      两边给出不同实词，至少一边错')
    print('    A缺/B缺   单侧整段缺失。比听错更危险——文字仍然通顺')
    print('    否定      「不」字之差，长度阈值查不到')
    print('    数字      没有冗余可推断，只能对着数')
    print()
    print('  但它只能定位分歧，不能判定谁对。两边同时错，这套方法永远查不出来。')
    line('━')


if __name__ == '__main__':
    main()
